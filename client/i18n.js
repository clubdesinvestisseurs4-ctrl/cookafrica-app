// Chargé comme script classique (pas type="module") AVANT app.js dans index.html —
// ce fichier ne connaît pas SITE (scopé au module app.js) ; c'est app.js qui appelle
// setI18nLang() juste après avoir calculé SITE, avant tout le reste.
let LANG = 'fr';
function setI18nLang(lang) { LANG = lang; }

// t(key, vars) — vars remplace les {placeholders} dans la chaîne trouvée.
function t(key, vars) {
  let str = (I18N[LANG] && I18N[LANG][key]) || I18N.fr[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(`{${k}}`, v);
    }
  }
  return str;
}

// Parcourt le DOM et traduit tout élément portant data-i18n / data-i18n-placeholder /
// data-i18n-title — appelé une fois au démarrage pour le HTML statique (le contenu
// généré dynamiquement par app.js utilise directement t() à la génération).
function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
}
